export function varGroups(docType: string, customPrices: string[] = []): { title: string; vars: string[] }[] {
  const common = [
    { title: "Компания", vars: COMPANY },
    { title: "Точка", vars: LOCATION },
    { title: "Сейчас", vars: NOW },
  ];
  switch (docType) {
    case "order":
    case "invoice":
      return [{ title: "Документ", vars: DOC }, { title: "Заказ", vars: ORDER }, { title: "Клиент", vars: CLIENT }, { title: "Итоги", vars: TOTALS }, { title: "Строка таблицы", vars: ITEM }, ...common];
    case "sale":
      return [{ title: "Документ", vars: DOC }, { title: "Клиент", vars: CLIENT }, { title: "Итоги", vars: TOTALS }, { title: "Строка таблицы", vars: ITEM }, ...common];
    case "price_tag":
      return [{ title: "Товар", vars: [...TAG, ...customPrices] }, ...common];
    case "salary":
      return [{ title: "Зарплата", vars: SALARY }, ...common];
    case "client_report":
      return [{ title: "Акт сверки", vars: REPORT }, { title: "Клиент", vars: CLIENT }, ...common];
    default:
      return [{ title: "Документ", vars: [...DOC, ...STOCK] }, { title: "Поставщик", vars: ["Контрагент", "ТелефоныКонтрагента"] }, { title: "Итоги", vars: TOTALS }, { title: "Строка таблицы", vars: ITEM }, ...common];
  }
}

